class MenuPDF(FPDF):
    def header(self):
        if self.page_no() == 1:
            return
        self.set_fill_color(*NAVY)
        self.rect(0, 0, self.w, self.h, "F")
        self.set_y(10)
        self.set_font("Brand", "B", 9)
        self.set_text_color(*GOLD)
        self.cell(0, 6, "STATION ONE CAFE  ·  МЕНЮ", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(*GOLD)
        self.set_line_width(0.3)
        self.line(18, self.get_y() + 1, self.w - 18, self.get_y() + 1)
        self.ln(8)

    def footer(self):
        if self.page_no() == 1:
            return
        self.set_y(-12)
        self.set_font("Brand", "", 8)
        self.set_text_color(*SILVER)
        self.cell(0, 6, f"Цены в BYN  ·  стр. {self.page_no() - 1}", align="C")


def make_menu_gradient_title(path: Path) -> Path:
    """Render large МЕНЮ with vertical gold → champagne → deep gold gradient."""
    from PIL import Image, ImageDraw, ImageFont

    W, H = 1600, 520
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    # Gradient band
    grad = Image.new("RGB", (W, H))
    gdraw = ImageDraw.Draw(grad)
    # stops: deep gold → vibrant gold → champagne → vibrant → deep
    stops = [
        (0.0, GOLD_DEEP),
        (0.25, GOLD),
        (0.5, CHAMPAGNE),
        (0.75, GOLD),
        (1.0, GOLD_DEEP),
    ]

    def lerp(a, b, t):
        return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))

    for y in range(H):
        t = y / (H - 1)
        for i in range(len(stops) - 1):
            t0, c0 = stops[i]
            t1, c1 = stops[i + 1]
            if t0 <= t <= t1:
                local = (t - t0) / (t1 - t0) if t1 > t0 else 0
                color = lerp(c0, c1, local)
                gdraw.line([(0, y), (W, y)], fill=color)
                break

    try:
        font = ImageFont.truetype(r"C:\Windows\Fonts\arialbd.ttf", 280)
    except OSError:
        font = ImageFont.load_default()

    mask = Image.new("L", (W, H), 0)
    mdraw = ImageDraw.Draw(mask)
    text = "МЕНЮ"
    bbox = mdraw.textbbox((0, 0), text, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    x = (W - tw) // 2 - bbox[0]
    y = (H - th) // 2 - bbox[1]
    mdraw.text((x, y), text, font=font, fill=255)

    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    out.paste(grad, (0, 0))
    out.putalpha(mask)
    path.parent.mkdir(parents=True, exist_ok=True)
    out.save(path)
    return path


